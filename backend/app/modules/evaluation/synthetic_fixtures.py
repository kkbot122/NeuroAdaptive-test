"""
Synthetic test-fixture data for demonstrating the evaluation harness --
NEVER real learner data, and NEVER wired into any FastAPI router or other
production-reachable code path (verified by
tests/evaluation/test_no_fabrication_guardrail.py, which greps every router
module for an import of this file and fails if one exists).

Every artifact this module's demo-report function produces carries the
label "SYNTHETIC TEST FIXTURE DATA -- NOT REAL LEARNERS" in its own title,
per the mandate: "If asked to 'show what the results would look like,'
decline to fabricate and instead show the harness computing real metrics
against a small synthetic FIXTURE dataset you construct and label
explicitly as synthetic test data."
"""
from datetime import datetime, timedelta, timezone
from typing import List

from app.modules.evaluation import metrics
from app.modules.mastery.engine import EvidenceEvent

SYNTHETIC_LABEL = "SYNTHETIC TEST FIXTURE DATA -- NOT REAL LEARNERS"


def synthetic_mastery_events(n: int = 5) -> List[EvidenceEvent]:
    """n hand-constructed, clearly fake evidence events -- correctness
    improves over time so a demo has something to show, not because this
    reflects any real learner's trajectory."""
    now = datetime(2026, 1, 1, tzinfo=timezone.utc)
    return [
        EvidenceEvent(
            correctness=min(1.0, 0.2 * (i + 1)),
            evidence_weight_base=1.0,
            created_at=now + timedelta(days=i),
        )
        for i in range(n)
    ]


def synthetic_citation_records(n_valid_supported: int = 6, n_valid_unsupported: int = 2, n_invalid: int = 2):
    records = (
        [metrics.CitationRecord(tier1_valid=True, tier2_supported=True) for _ in range(n_valid_supported)]
        + [metrics.CitationRecord(tier1_valid=True, tier2_supported=False) for _ in range(n_valid_unsupported)]
        + [metrics.CitationRecord(tier1_valid=False, tier2_supported=None) for _ in range(n_invalid)]
    )
    return records


def build_synthetic_demo_report() -> dict:
    """
    Runs the REAL harness (metrics.py, unmodified) against synthetic
    fixture data only. The label is baked into the return value's own
    "title" field, not left to a caller to remember to add -- so any
    consumer of this dict (a script, a notebook, a demo page) sees it
    without extra effort.
    """
    now = datetime(2026, 1, 6, tzinfo=timezone.utc)
    events = synthetic_mastery_events()
    mastery_state = metrics.compute_mastery_state(events, now)
    t2m = metrics.time_to_mastery(events, now)
    a2m = metrics.attempts_to_mastery(events, now)

    citations = synthetic_citation_records()
    citation_result = metrics.citation_precision_recall(citations)

    latencies = [0.10, 0.12, 0.15, 0.20, 0.35, 0.50, 0.11, 0.13, 0.90, 0.14]
    latency_result = metrics.latency_percentiles(latencies)

    return {
        "title": SYNTHETIC_LABEL,
        "caption": (
            f"{SYNTHETIC_LABEL}. Generated by build_synthetic_demo_report() to "
            "demonstrate the Phase 8 harness computing real metric functions "
            "against fabricated input -- this is not a claim about any real "
            "learner, cohort, or deployment."
        ),
        "mastery": {"mastery": mastery_state.mastery, "uncertainty": mastery_state.uncertainty},
        "time_to_mastery_seconds": t2m,
        "attempts_to_mastery": a2m,
        "citation_precision_recall": citation_result.__dict__,
        "latency_percentiles": latency_result.__dict__,
    }
